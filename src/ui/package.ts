// ─── Code Connect package assembly (Dev Mode publish fallback) ───
//
// The main thread gathers each scoped set's draft + contract (gatherDownloadPackage)
// and posts a DownloadPackage; this turns that payload into the archive's files, which
// download.ts ZIPs and hands to the browser. Parserless Code Connect: `.figma.ts`
// template files published with `figma connect publish` — never the deprecated
// `figma.connect()` parser format.
//
// The one structural decision here: a figma.config.json's `label` is single-valued and
// applies to a whole publish, so the LABEL is the publish boundary. We partition the
// templates by their `// label=` frontmatter into one publishable unit per label — flat
// when there's a single label, one `<label>/` subfolder each when there's more. Config
// `label`/`language` are projected from the templates' `// label=` / `// language=`
// headers, so the frontmatter stays the single source of truth.

import type { ZipEntry } from './download'

export interface PackageComponent {
  component: string
  label: string
  language: string
  template: string
  contract: unknown | null
}

export interface DownloadPackage {
  fileKey: string
  library: string
  generatedAt: string
  components: PackageComponent[]
}

// A filesystem-safe path segment from a component/set/label name (names can carry
// '/', ':', etc.). Never empty.
export function safeSegment(name: string): string {
  const cleaned = name
    .replace(/[\\/:*?"<>|\x00-\x1f]+/g, '-')
    .replace(/^\.+/, '')
    .replace(/\s+/g, ' ')
    .trim()
  return cleaned || 'component'
}

// Fallbacks for a draft that never authored a `// label=` / `// language=` header
// (the ext.labelHint / ext.languageHint conventions nudge toward setting them). The
// label default matches the historical config value; the language default suits the
// JSX/TS snippets these templates carry.
const DEFAULT_CONFIG_LABEL = 'React'
const DEFAULT_CONFIG_LANGUAGE = 'jsx'

// One figma.config.json for a publish unit (a single label). `include` globs that
// unit's template files; `label`/`language` are projected from the templates'
// frontmatter and only affect how snippets are labelled in Figma (the README says
// how to retune them).
function configJson(label: string, language: string): string {
  return (
    JSON.stringify(
      {
        codeConnect: {
          include: ['**/*.figma.ts'],
          label: label || DEFAULT_CONFIG_LABEL,
          language: language || DEFAULT_CONFIG_LANGUAGE,
        },
      },
      null,
      2,
    ) + '\n'
  )
}

// A manifest row for the README — a template's published address, its path in the
// archive, and its (top-level) contract path if any.
interface ManifestRow {
  c: PackageComponent
  path: string
  contract: string | null
}

// The README that ships at the package root: what it is, the file it came from, the
// publish command(s) — one when flat, a per-label loop when split — and the
// per-template manifest, grouped to mirror the folder layout.
function authorReadme(
  pkg: DownloadPackage,
  groups: Array<{ label: string; items: PackageComponent[] }>,
  flat: boolean,
  manifest: ManifestRow[],
): string {
  const fileLine = pkg.fileKey
    ? `From file [${pkg.fileKey}](https://www.figma.com/design/${pkg.fileKey}).`
    : `File key not set — add the target file’s URL in each template’s \`// url=\` header before publishing.`
  const lines = [
    '# Code Connect package',
    '',
    `Generated by the cc-processor plugin on ${pkg.generatedAt}.`,
    fileLine,
    '',
    'This holds parserless Code Connect **template files** (`.figma.ts`); each one’s',
    'source contract sits in `contracts/` for reference (the CLI ignores it — it isn’t',
    'matched by the config’s glob).',
    '',
  ]

  if (flat) {
    lines.push(
      'Publish them to Figma from your terminal:',
      '',
      '```sh',
      '# from this folder — requires a Figma token with Code Connect write access',
      'export FIGMA_ACCESS_TOKEN=<your token>',
      'npx figma connect publish',
      '```',
      '',
    )
  } else {
    lines.push(
      'A `figma.config.json`’s `label` applies to a whole publish, so templates are',
      'grouped into one subfolder per **label**, each with its own config. Publish',
      'every group:',
      '',
      '```sh',
      '# from this folder — requires a Figma token with Code Connect write access',
      'export FIGMA_ACCESS_TOKEN=<your token>',
      'for d in */; do [ -f "$d/figma.config.json" ] && (cd "$d" && npx figma connect publish); done',
      '```',
      '',
      'Or publish one label alone by `cd`-ing into its folder and running',
      '`npx figma connect publish` there.',
      '',
    )
  }

  lines.push(
    'Preview without publishing with `npx figma connect preview` (needs a PAT — see',
    'below). Each config’s',
    '`label` and `language` come from the templates’ `// label=` and `// language=`',
    'headers — adjust the headers (or the config) to match your codebase.',
    '',
    '## CLI tokens: PLANT vs. PAT',
    '',
    'The CLI reads its Figma token from the `FIGMA_ACCESS_TOKEN` env var above. Two',
    'token types exist and the `figma connect` commands do **not** accept them',
    'interchangeably:',
    '',
    '- **PLANT** — a project-scoped token. `figma connect publish` and',
    '  `figma connect unpublish` accept it, so the publish commands above work with a',
    '  PLANT alone.',
    '- **PAT** — a personal access token with Code Connect write scope. The other',
    '  `figma connect` commands (e.g. `preview`, `create`, `parse`) reject a PLANT and',
    '  require a PAT.',
    '',
    'If a command fails with `403: Invalid Token Type`, the token you exported isn’t',
    'accepted for that command — re-export `FIGMA_ACCESS_TOKEN` with a PAT and run it',
    'again:',
    '',
    '```sh',
    'export FIGMA_ACCESS_TOKEN=<your personal access token>',
    '```',
    '',
    '## Updating the CLI',
    '',
    'These commands run the Code Connect CLI from the `@figma/code-connect` package.',
    'Pull the latest version before publishing so you’re on current behavior:',
    '',
    '```sh',
    'npm install @figma/code-connect@latest',
    '```',
    '',
    'Not using a local install? Force npx to fetch the latest instead of a cached',
    'copy with `npx @figma/code-connect@latest connect publish`. Check your version',
    'any time with `npx figma --version`.',
    '',
    '## Templates',
    '',
  )

  for (const g of groups) {
    if (!flat) lines.push(`### ${g.label || 'unlabeled'}`, '')
    for (const m of manifest) {
      if ((m.c.label || '').trim() !== g.label) continue
      const addr = m.c.label ? `${m.c.component}/${m.c.label}` : m.c.component
      const contract = m.contract ? ` · contract: \`${m.contract}\`` : ''
      lines.push(`- **${addr}** → \`${m.path}\`${contract}`)
    }
    if (!flat) lines.push('')
  }
  lines.push('')
  return lines.join('\n')
}

// Turn the payload into the archive's files. Templates are partitioned by their
// `// label=` — the publish boundary, since a figma.config.json's label is
// single-valued — into one publishable unit per label, each with its own config.
// A single-label run stays flat (no subfolders); multiple labels split into
// `<label>/` subfolders. Contracts are reference-only, so they live once under a
// shared top-level `contracts/` (deduped by component, even across labels).
// Everything nests under one `code-connect/` folder — the unzipped root.
export function assemblePackageEntries(pkg: DownloadPackage): ZipEntry[] {
  const ROOT = 'code-connect/'
  const entries: ZipEntry[] = []

  // ── Partition by label, preserving first-appearance order ──
  const groups: Array<{ label: string; items: PackageComponent[] }> = []
  const byLabel = new Map<string, PackageComponent[]>()
  for (const c of pkg.components) {
    const label = (c.label || '').trim()
    let items = byLabel.get(label)
    if (!items) {
      items = []
      byLabel.set(label, items)
      groups.push({ label, items })
    }
    items.push(c)
  }
  // Stay flat until a second label forces the split.
  const flat = groups.length <= 1

  // ── Contracts: reference-only, deduped, top-level ──
  // Written once per component (a component published under two labels still has one
  // contract); the returned path is what the README links to.
  const contractName = new Map<string, string>() // component → filename base
  const contractTaken = new Set<string>()
  const contractPath = (c: PackageComponent): string | null => {
    if (c.contract == null) return null
    let name = contractName.get(c.component)
    if (!name) {
      const b = safeSegment(c.component)
      name = b
      for (let i = 2; contractTaken.has(name); i++) name = `${b}-${i}`
      contractTaken.add(name)
      contractName.set(c.component, name)
      entries.push({ path: `${ROOT}contracts/${name}.contract.json`, text: JSON.stringify(c.contract, null, 2) + '\n' })
    }
    return `contracts/${name}.contract.json`
  }

  // ── Templates + one config per publish unit ──
  const dirTaken = new Set<string>()
  const manifest: ManifestRow[] = []
  for (const g of groups) {
    // Flat runs live at the root; split runs get a labelled subfolder.
    let dir = ''
    if (!flat) {
      const b = safeSegment(g.label || 'unlabeled')
      dir = b
      for (let i = 2; dirTaken.has(dir); i++) dir = `${b}-${i}`
      dirTaken.add(dir)
      dir += '/'
    }
    const fileTaken = new Set<string>() // template filenames unique within the unit
    let language = ''
    for (const c of g.items) {
      const b = safeSegment(c.component)
      let name = `${b}.figma.ts`
      for (let i = 2; fileTaken.has(name); i++) name = `${b}-${i}.figma.ts`
      fileTaken.add(name)
      entries.push({ path: `${ROOT}${dir}${name}`, text: c.template.replace(/\s*$/, '') + '\n' })
      manifest.push({ c, path: `${dir}${name}`, contract: contractPath(c) })
      // The config's language is the group's first authored one (they should agree).
      if (!language && (c.language || '').trim()) language = c.language.trim()
    }
    entries.push({ path: `${ROOT}${dir}figma.config.json`, text: configJson(g.label, language) })
  }

  entries.push({ path: `${ROOT}README.md`, text: authorReadme(pkg, groups, flat, manifest) })
  return entries
}
